CREATE TABLE
    ADMISSION (
        ADMISSION_ID NUMBER GENERATED ALWAYS AS IDENTITY NOT NULL,
        PATIENT_ID NUMBER NOT NULL,
        ROOM_ID NUMBER NOT NULL,
        ADMIT_DATE DATE NOT NULL,
        DISCHARGE_DATE DATE,
        STATUS VARCHAR2 (20) DEFAULT 'Admitted' NOT NULL,
        CONSTRAINT CHK_ADMISSION_STATUS CHECK (status IN ('Admitted', 'Discharged')),
        PRIMARY KEY (ADMISSION_ID),
        CONSTRAINT UQ_ADMISSION_ID_PATIENT UNIQUE (ADMISSION_ID, PATIENT_ID)
    );

CREATE TABLE
    APPOINTMENT (
        APPOINTMENT_ID NUMBER GENERATED ALWAYS AS IDENTITY NOT NULL,
        PATIENT_ID NUMBER NOT NULL,
        DOCTOR_ID NUMBER NOT NULL,
        SCHEDULED_AT TIMESTAMP(6) NOT NULL,
        STATUS VARCHAR2 (20) DEFAULT 'Scheduled' NOT NULL,
        CONSTRAINT CHK_APPT_STATUS CHECK (status IN ('Scheduled', 'Completed', 'Cancelled')),
        PRIMARY KEY (APPOINTMENT_ID),
        CONSTRAINT UQ_APPT_ID_PATIENT UNIQUE (APPOINTMENT_ID, PATIENT_ID)
    );

CREATE TABLE
    BILL (
        BILL_ID NUMBER GENERATED ALWAYS AS IDENTITY NOT NULL,
        PATIENT_ID NUMBER NOT NULL,
        ADMISSION_ID NUMBER,
        AMOUNT NUMBER (10, 2) DEFAULT 0 NOT NULL,
        STATUS VARCHAR2 (20) DEFAULT 'Open' NOT NULL,
        APPOINTMENT_ID NUMBER,
        CONSTRAINT CHK_BILL_STATUS CHECK (status IN ('Open', 'Paid', 'Overdue')),
        PRIMARY KEY (BILL_ID),
        CONSTRAINT CHK_BILL_ONE_ENCOUNTER CHECK (
            (
                appointment_id IS NOT NULL
                AND admission_id IS NULL
            )
            OR (
                appointment_id IS NULL
                AND admission_id IS NOT NULL
            )
        )
    );

CREATE TABLE
    CARE_ASSIGNMENT (
        ASSIGNMENT_ID NUMBER GENERATED ALWAYS AS IDENTITY NOT NULL,
        PATIENT_ID NUMBER NOT NULL,
        DOCTOR_ID NUMBER NOT NULL,
        START_DATE DATE NOT NULL,
        END_DATE DATE,
        STATUS VARCHAR2 (20) DEFAULT 'Active' NOT NULL,
        CONSTRAINT CHK_CARE_STATUS CHECK (status IN ('Active', 'Ended', 'Transferred')),
        PRIMARY KEY (ASSIGNMENT_ID)
    );

CREATE TABLE
    DEPARTMENT (
        DEPARTMENT_ID NUMBER GENERATED ALWAYS AS IDENTITY NOT NULL,
        NAME VARCHAR2 (100) NOT NULL,
        LOCATION VARCHAR2 (100),
        PRIMARY KEY (DEPARTMENT_ID)
    );

CREATE TABLE
    DISPENSING (
        DISPENSE_ID NUMBER GENERATED ALWAYS AS IDENTITY NOT NULL,
        PRESCRIPTION_ID NUMBER NOT NULL,
        PHARMACIST_ID NUMBER NOT NULL,
        BILL_ID NUMBER,
        DISPENSE_DATE DATE DEFAULT SYSDATE NOT NULL,
        STATUS VARCHAR2 (20) DEFAULT 'Dispensed' NOT NULL,
        MEDICATION_QUANTITY NUMBER NOT NULL,
        CONSTRAINT CHK_DISPENSING_STATUS CHECK (status IN ('Dispensed', 'Cancelled')),
        PRIMARY KEY (DISPENSE_ID)
    );

CREATE TABLE
    DOCTOR (
        DOCTOR_ID NUMBER GENERATED ALWAYS AS IDENTITY NOT NULL,
        STAFF_ID NUMBER NOT NULL,
        DEPARTMENT_ID NUMBER NOT NULL,
        SPECIALIZATION VARCHAR2 (100),
        IS_DEPARTMENT_HEAD NUMBER (1, 0) DEFAULT 0 NOT NULL,
        CONSTRAINT CHK_DOCTOR_HEAD CHECK (is_department_head IN (0, 1)),
        PRIMARY KEY (DOCTOR_ID),
        CONSTRAINT UQ_DOCTOR_STAFF UNIQUE (STAFF_ID)
    );

CREATE TABLE
    LAB_ORDER (
        ORDER_ID NUMBER GENERATED ALWAYS AS IDENTITY NOT NULL,
        PATIENT_ID NUMBER NOT NULL,
        DOCTOR_ID NUMBER NOT NULL,
        DEPARTMENT_ID NUMBER NOT NULL,
        TEST_TYPE VARCHAR2 (100) NOT NULL,
        ORDER_DATE DATE DEFAULT SYSDATE NOT NULL,
        STATUS VARCHAR2 (20) DEFAULT 'Ordered' NOT NULL,
        CONSTRAINT CHK_LAB_ORDER_STATUS CHECK (
            status IN ('Ordered', 'InProgress', 'Completed', 'Cancelled')
        ),
        PRIMARY KEY (ORDER_ID)
    );

CREATE TABLE
    LAB_RESULT (
        RESULT_ID NUMBER GENERATED ALWAYS AS IDENTITY NOT NULL,
        ORDER_ID NUMBER NOT NULL,
        RESULT_VALUE VARCHAR2 (500),
        RESULT_DATE DATE,
        STATUS VARCHAR2 (20) DEFAULT 'Pending' NOT NULL,
        RELEASED_FLAG NUMBER (1, 0) DEFAULT 0 NOT NULL,
        CONSTRAINT CHK_LAB_RESULT_STATUS CHECK (status IN ('Pending', 'Final', 'Amended')),
        CONSTRAINT CHK_LAB_RELEASED CHECK (released_flag IN (0, 1)),
        PRIMARY KEY (RESULT_ID)
    );

CREATE TABLE
