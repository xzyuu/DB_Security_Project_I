-- =====================================================================
-- 02_sample_data.sql  -  data of the PROJ_ONE schema, exported from the live
-- database (17 tables, 292 rows), in foreign-key order.
--
-- Run as PROJ_ONE (the schema owner) on a database where the tables are
-- already created and EMPTY.  Data only: no CREATE TABLE, no VPD policies.
--
-- Primary keys are GENERATED ALWAYS AS IDENTITY, which refuses explicit IDs.
-- Section 1 therefore switches them to BY DEFAULT, section 3 switches them
-- back and moves each identity to MAX(id)+1.  MEDICAL_RECORD is already
-- BY DEFAULT and is left unchanged.
--
-- Accounts used by the tests (USER_DOCTOR1, USER_NURSE1, ...) are matched to
-- STAFF / PATIENT rows through ORACLE_USERNAME; the Oracle users and role
-- grants themselves are NOT created by this script.
-- =====================================================================
